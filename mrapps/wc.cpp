//
// a word-count application "plugin" for MapReduce.
//
// built by the Makefile into wc.so
//

#include <cctype>
#include <string>
#include <vector>

#include "mr/mr.h"

//
// The map function is called once for each file of input. The first
// argument is the name of the input file, and the second is the
// file's complete contents. You should ignore the input file name,
// and look only at the contents argument. The return value is a vector
// of key/value pairs.
//
static std::vector<mr::KeyValue> Map(const std::string& filename, const std::string& contents) {
    std::vector<mr::KeyValue> kva;
    std::string word;
    // words are runs of ASCII letters (Go's version also counts Unicode letters).
    for (unsigned char c : contents) {
        if (std::isalpha(c)) {
            word += c;
        } else if (!word.empty()) {
            kva.push_back({word, "1"});
            word.clear();
        }
    }
    if (!word.empty()) {
        kva.push_back({word, "1"});
    }
    return kva;
}

//
// The reduce function is called once for each key generated by the
// map tasks, with a list of all the values created for that key by
// any map task.
//
static std::string Reduce(const std::string& key, const std::vector<std::string>& values) {
    // return the number of occurrences of this word.
    return std::to_string(values.size());
}

extern "C" const mr::Plugin mr_plugin = {Map, Reduce};
