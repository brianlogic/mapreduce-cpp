//
// an indexing application "plugin" for MapReduce.
//
// built by the Makefile into indexer.so
//

#include <algorithm>
#include <cctype>
#include <set>
#include <string>
#include <vector>

#include "mr/mr.h"

//
// The mapping function is called once for each piece of the input.
// In this framework, the key is the name of the file that is being processed,
// and the value is the file's contents. The return value should be a vector of
// key/value pairs, each represented by a mr::KeyValue.
//
static std::vector<mr::KeyValue> Map(const std::string& document, const std::string& value) {
    std::set<std::string> words;
    std::string word;
    for (unsigned char c : value) {
        if (std::isalpha(c)) {
            word += c;
        } else if (!word.empty()) {
            words.insert(word);
            word.clear();
        }
    }
    if (!word.empty()) {
        words.insert(word);
    }

    std::vector<mr::KeyValue> res;
    for (const std::string& w : words) {
        res.push_back({w, document});
    }
    return res;
}

//
// The reduce function is called once for each key generated by Map, with a
// list of that key's string value (merged across all inputs). The return value
// should be a single output value for that key.
//
static std::string Reduce(const std::string& key, const std::vector<std::string>& values) {
    std::vector<std::string> vv = values;
    std::sort(vv.begin(), vv.end());
    std::string joined;
    for (size_t i = 0; i < vv.size(); i++) {
        if (i > 0) {
            joined += ",";
        }
        joined += vv[i];
    }
    return std::to_string(vv.size()) + " " + joined;
}

extern "C" const mr::Plugin mr_plugin = {Map, Reduce};
